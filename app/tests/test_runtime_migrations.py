"""Exercise autogeneration and fresh installation on isolated PostgreSQL schemas."""

import os
from pathlib import Path
import shutil
import tempfile
import unittest
from unittest.mock import patch
from uuid import uuid4

from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from alembic.script import ScriptDirectory
from sqlalchemy import CheckConstraint, Column, Text, inspect, select
from sqlalchemy.schema import DropSchema

from rag.runtime._config import RuntimeSettings
from rag.runtime.lifecycle import _engine, _migration_config, migrate_runtime
from rag.runtime.postgresql._models import _CorpusState, _Employee


class MigrationHistoryTests(unittest.TestCase):
    def test_migration_chain_has_one_base_and_one_head(self):
        scripts = ScriptDirectory.from_config(_migration_config())
        revisions = list(scripts.walk_revisions())
        self.assertEqual([revision.revision for revision in revisions], ["003_mini_app", "002_ticket_resources", "001_initial"])
        self.assertEqual(revisions[0].down_revision, '002_ticket_resources')
        self.assertIsNone(revisions[-1].down_revision)


@unittest.skipUnless(os.environ.get("RUN_MIGRATION_INTEGRATION") == "1",
                     "Set RUN_MIGRATION_INTEGRATION=1 and PostgreSQL environment")
class MigrationIntegrationTests(unittest.IsolatedAsyncioTestCase):
    async def test_install_autogenerate_upgrade_and_roundtrip(self):
        schema = "migration_test_" + uuid4().hex
        with patch.dict(os.environ, {"RAG_PG_SCHEMA": schema}):
            engine = _engine(RuntimeSettings())
            try:
                await migrate_runtime()
                await migrate_runtime()
                baseline = ScriptDirectory.from_config(_migration_config()).get_current_head()
                config = _migration_config()

                async def run(action):
                    async with engine.begin() as connection:
                        def invoke(sync_connection):
                            config.attributes.update(connection=sync_connection, schema=schema)
                            action(config)
                        await connection.run_sync(invoke)

                await run(command.check)
                async with engine.connect() as connection:
                    self.assertEqual(await connection.scalar(select(_CorpusState.generation)), 0)
                    foreign_keys = await connection.run_sync(
                        lambda c: inspect(c).get_foreign_keys("documents"))
                    self.assertIn("documents_current_revision_fk", [fk["name"] for fk in foreign_keys])

                # Generate a real follow-up revision without changing tracked files.
                with tempfile.TemporaryDirectory() as directory:
                    migrations = Path(__file__).parents[1] / "rag/runtime/_migrations"
                    shutil.copytree(migrations, directory, dirs_exist_ok=True,
                                    ignore=shutil.ignore_patterns("__pycache__"))
                    config = Config()
                    config.set_main_option("script_location", directory)
                    column = Column("migration_test_note", Text, nullable=True)
                    _Employee.__table__.append_column(column)
                    constraint = CheckConstraint(
                        "migration_test_note IS NULL OR length(migration_test_note)>0",
                        name="employees_migration_test_note_nonempty")
                    _Employee.__table__.append_constraint(constraint)
                    try:
                        with self.assertRaises(AutogenerateDiffsDetected):
                            await run(command.check)
                        await run(lambda cfg: command.revision(
                            cfg, message="test extra column", autogenerate=True))
                        await run(lambda cfg: command.upgrade(cfg, "head"))
                        await run(command.check)
                        await run(lambda cfg: command.downgrade(cfg, baseline))
                    finally:
                        _Employee.__table__._columns.remove(column)
                        _Employee.__table__.constraints.remove(constraint)

                config = _migration_config()
                await run(command.check)
                await run(lambda cfg: command.downgrade(cfg, "base"))
                await migrate_runtime()
                await run(command.check)
            finally:
                async with engine.begin() as connection:
                    await connection.execute(DropSchema(schema, cascade=True))
                await engine.dispose()

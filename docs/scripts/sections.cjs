const fs = require('node:fs');
const path = require('node:path');
const yaml = require('js-yaml');

// Top-level folders are sections; nested folders belong to their section's sidebar.
const root = path.join(__dirname, '../documents');
function containsDocuments(directory) {
  return fs.readdirSync(directory, {withFileTypes: true}).some((entry) =>
    entry.isDirectory()
      ? containsDocuments(path.join(directory, entry.name))
      : /\.mdx?$/.test(entry.name),
  );
}
const sections = fs.readdirSync(root, {withFileTypes: true})
  .filter((entry) => entry.isDirectory())
  .map(({name}) => {
    if (!/^[a-z][a-z0-9-]*$/.test(name)) {
      throw new Error(`Section folder must use lowercase Latin letters, digits and hyphens: ${name}`);
    }
    const file = path.join(root, name, '_category_.yml');
    const metadata = yaml.load(fs.readFileSync(file, 'utf8'));
    if (!metadata || typeof metadata.label !== 'string' || !metadata.label.trim() ||
        !Number.isFinite(metadata.position)) {
      throw new Error(`${file}: label and numeric position are required`);
    }
    return {
      name, label: metadata.label, position: metadata.position,
      hasDocuments: containsDocuments(path.join(root, name)),
    };
  })
  .filter(({hasDocuments}) => hasDocuments)
  .sort((a, b) => a.position - b.position || a.name.localeCompare(b.name));

exports.sections = sections;
exports.sidebars = Object.fromEntries(sections.map(({name}) => [name, [
  {type: 'autogenerated', dirName: name},
]]));
exports.navbarItems = sections.map(({name, label}) => ({
  type: 'docSidebar', sidebarId: name, label, position: 'left',
}));
